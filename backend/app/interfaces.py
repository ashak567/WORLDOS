"""Future capabilities stay behind contracts until deterministic facts support them."""
from __future__ import annotations

from typing import Protocol


class ScenarioEngine(Protocol):
    """Engine 16: Deterministic Scenario Engine."""

    def validate_constraints(self, scenario: dict) -> list[str]: ...
    def validate_scenario(self, scenario_id: str) -> dict: ...
    def evaluate_scenario(self, scenario_id: str) -> dict: ...
    def branch_scenario(self, scenario_id: str, new_name: str) -> dict: ...



class PredictionEngine(Protocol):
    """Engine 18: Bounded Deterministic Prediction Engine Protocol."""

    def predict(self, request: Any, conn: Any = None) -> Any: ...
    def list_runs(self, **kwargs: Any) -> list[Any]: ...
    def get_run(self, run_id: Any, conn: Any = None) -> Any: ...
    def get_trajectory(self, run_id: Any, **kwargs: Any) -> list[Any]: ...
    def evaluate_run(self, run_id: Any, conn: Any = None) -> Any: ...
    def get_evaluation(self, run_id: Any, conn: Any = None) -> Any: ...
    def run_backtest(self, request: Any, conn: Any = None) -> Any: ...
    def list_methods(self) -> list[Any]: ...


class SimulationEngine(Protocol):
    """Engine 17: Bounded Deterministic Forward Simulation Engine."""

    def run(self, scenario: dict) -> dict: ...
    def create_simulation(self, request: Any, conn: Any = None) -> Any: ...
    def run_simulation(self, simulation_id: Any, conn: Any = None) -> Any: ...
    def get_simulation(self, simulation_id: Any, conn: Any = None) -> Any: ...
    def list_simulations(self, **kwargs: Any) -> list[Any]: ...
    def get_trajectory(self, simulation_id: Any, **kwargs: Any) -> list[Any]: ...
    def compare_simulations(self, sim_a_id: Any, sim_b_id: Any, conn: Any = None) -> Any: ...


class AnomalyEngine(Protocol):
    """Engine 15: Anomaly Detection Engine Protocol."""

    def detect(self, request: Any, conn: Any = None) -> Any: ...
    def list_runs(self, **kwargs: Any) -> list[Any]: ...
    def get_run(self, run_id: Any, conn: Any = None) -> Any: ...
    def list_findings(self, **kwargs: Any) -> list[Any]: ...
    def get_finding(self, finding_id: Any, conn: Any = None) -> Any: ...
    def suppress_finding(self, finding_id: Any, notes: str | None = None, conn: Any = None) -> Any: ...
    def resolve_finding(self, finding_id: Any, notes: str | None = None, conn: Any = None) -> Any: ...
    def list_methods(self) -> list[Any]: ...


class EvidenceBoundReasoner(Protocol):
    def answer(self, question: str, deterministic_result: dict, evidence_ids: list[str]) -> dict: ...


class DecisionSupportEngine(Protocol):
    """Engine 13: Deterministic Decision Support Engine."""

    def evaluate(self, request: dict) -> dict: ...

